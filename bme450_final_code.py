hooks = []
for layer in [model.conv1, model.conv2, model.conv3, model.conv4]:
    hooks.append(layer.register_forward_hook(hook_fn))

# Forward pass
model.eval()
with torch.no_grad():
    _ = model(input_tensor)

# Remove hooks
for hook in hooks:
    hook.remove()

# Now plot feature maps
for layer, activations in activation_maps.items():
    activations = activations.squeeze(0).cpu()  # remove batch dimension
    num_feature_maps = activations.shape[0]
    cols = 8
    rows = (num_feature_maps + cols - 1) // cols

    fig, axes = plt.subplots(rows, cols, figsize=(20, 8))
    fig.suptitle(f'Feature Maps after {layer.__class__.__name__}', fontsize=18)

    for idx in range(rows * cols):
        ax = axes[idx // cols, idx % cols]
        if idx < num_feature_maps:
            ax.imshow(activations[idx], cmap='viridis')
